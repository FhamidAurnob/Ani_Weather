package com.example.wuwaweather.data

/** OpenWeather has no Bangla, so we translate its condition codes ourselves. */
object BanglaWeather {
    fun describe(id: Int?): String? = when (id) {
        null -> null
        in 200..202 -> "বজ্রসহ বৃষ্টি"
        in 210..221 -> "বজ্রঝড়"
        in 230..232 -> "বজ্রসহ গুঁড়ি গুঁড়ি বৃষ্টি"
        in 300..321 -> "গুঁড়ি গুঁড়ি বৃষ্টি"
        500 -> "হালকা বৃষ্টি"
        501 -> "মাঝারি বৃষ্টি"
        502 -> "ভারী বৃষ্টি"
        503, 504 -> "অতি ভারী বৃষ্টি"
        511 -> "হিমশীতল বৃষ্টি"
        520, 521 -> "থেমে থেমে বৃষ্টি"
        522, 531 -> "ভারী ঝুম বৃষ্টি"
        in 600..622 -> "তুষারপাত"
        701 -> "হালকা কুয়াশা"
        711 -> "ধোঁয়া"
        721 -> "ধোঁয়াশা"
        731, 761 -> "ধুলো"
        741 -> "ঘন কুয়াশা"
        751 -> "বালুঝড়"
        762 -> "আগ্নেয় ছাই"
        771 -> "দমকা হাওয়া"
        781 -> "টর্নেডো"
        800 -> "পরিষ্কার আকাশ"
        801 -> "সামান্য মেঘ"
        802 -> "আংশিক মেঘলা"
        803 -> "বেশ মেঘলা"
        804 -> "মেঘাচ্ছন্ন আকাশ"
        else -> null
    }
}
